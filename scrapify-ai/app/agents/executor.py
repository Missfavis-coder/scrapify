
from typing import Any


class Executor:
    """
    Executes validated actions through the browser layer.

    Accepts actions generated by Scrapify's planner:
    {
        "type": "navigate",
        "parameters": {"url": "https://example.com"}
    }
    """

    def __init__(self, browser):
        self.browser = browser

    async def execute(
        self,
        action: dict[str, Any],
    ) -> dict[str, Any]:
        if not isinstance(action, dict):
            return {
                "success": False,
                "error": "Action must be an object.",
            }

        action_type = action.get("type")
        parameters = action.get("parameters", {})

        if not isinstance(action_type, str) or not action_type:
            return {
                "success": False,
                "error": "Action type is missing.",
            }

        if not isinstance(parameters, dict):
            return {
                "success": False,
                "action": action,
                "error": "Action parameters must be an object.",
            }

        try:
            if action_type in ("navigate", "open_url"):
                url = parameters.get("url") or action.get("url")

                if not isinstance(url, str) or not url.strip():
                    raise ValueError(
                        "Navigate action requires a URL."
                    )

                await self.browser.open_url(url)

                return {
                    "success": True,
                    "action": action,
                }

            elif action_type == "search":
                query = parameters.get("query") or action.get("query")

                if not isinstance(query, str) or not query.strip():
                    raise ValueError(
                        "Search action requires a query."
                    )

                await self.browser.search(query)

                return {
                    "success": True,
                    "action": action,
                }

            elif action_type == "click":
                selector = parameters.get("selector") or action.get("selector")

                if not isinstance(selector, str) or not selector.strip():
                    raise ValueError(
                        "Click action requires a selector."
                    )

                await self.browser.click(selector)

                return {
                    "success": True,
                    "action": action,
                }

            elif action_type == "fill":
                selector = parameters.get("selector")
                value = parameters.get("value")

                if not isinstance(selector, str) or not selector.strip():
                    raise ValueError(
                        "Fill action requires a selector."
                    )

                if not isinstance(value, str):
                    raise ValueError(
                        "Fill action requires a string value."
                    )

                await self.browser.fill(selector, value)

                return {
                    "success": True,
                    "action": action,
                }

            elif action_type == "extract":
                fields = parameters.get("fields", [])

                if (
                    not isinstance(fields, list)
                    or not all(isinstance(field, str) for field in fields)
                ):
                    raise ValueError(
                        "Extract action requires fields to be a "
                        "list of strings."
                    )

                data = await self.browser.extract(fields)

                return {
                    "success": True,
                    "action": action,
                    "data": data,
                }

            elif action_type == "paginate":
                fields = parameters.get("fields", ["products"])
                next_selector = parameters.get("next_selector")
                max_pages = parameters.get("max_pages", 5)

                if (
                    not isinstance(fields, list)
                    or not all(isinstance(field, str) for field in fields)
                ):
                    raise ValueError(
                        "Paginate action requires fields to be a "
                        "list of strings."
                    )

                if next_selector is not None and (
                    not isinstance(next_selector, str)
                    or not next_selector.strip()
                ):
                    raise ValueError(
                        "next_selector must be a non-empty CSS selector."
                    )

                if (
                    isinstance(max_pages, bool)
                    or not isinstance(max_pages, int)
                    or not 1 <= max_pages <= 20
                ):
                    raise ValueError(
                        "max_pages must be an integer between 1 and 20."
                    )

                data = await self.browser.paginate(
                    fields=fields,
                    next_selector=next_selector,
                    max_pages=max_pages,
                )

                return {
                    "success": True,
                    "action": action,
                    "data": data,
                }

            elif action_type == "scroll":
                direction = parameters.get("direction")

                if direction not in ("up", "down"):
                    raise ValueError(
                        "Scroll direction must be 'up' or 'down'."
                    )

                await self.browser.scroll(direction)

                return {
                    "success": True,
                    "action": action,
                }

            elif action_type == "wait":
                seconds = parameters.get("seconds", 2)

                if (
                    isinstance(seconds, bool)
                    or not isinstance(seconds, (int, float))
                    or seconds < 0
                ):
                    raise ValueError(
                        "Wait seconds must be a non-negative number."
                    )

                await self.browser.wait(seconds)

                return {
                    "success": True,
                    "action": action,
                }

            else:
                return {
                    "success": False,
                    "action": action,
                    "error": f"Unsupported action: {action_type}",
                }

        except Exception as exc:
            return {
                "success": False,
                "action": action,
                "error": str(exc),
            }
